/**
 * 表单状态。
 *
 * 单独一个文件，不是放在 actions.ts 里的 —— `"use server"` 模块**只能导出
 * 异步函数**，多导出一个常量会让整个文件在构建时报错。类型本身是擦除的，放哪
 * 都行，但初始值是个真实的值，必须搬出来。与 lib/auth/form-state.ts 同构。
 */

export type AddFriendFormState = {
  /**
   * 手机号字段下方的错误。
   *
   * 只有两种情况下会出现：号码形状不对（不是 11 位手机号），以及加的是自己。
   * 两者都不泄漏「这个号码注册过没有」—— 前者是纯格式判断，后者用的是调用者
   * 自己的号码，信息量为零。
   */
  phoneError?: string;
  /**
   * 提交后的回执。**它不区分成功与失败，这是设计的一部分，不是偷懒。**
   *
   * 「请求已发出」「号码没注册」「对方还没取名」「本来就是好友」几种结果返回的是
   * 同一个字符串，所以**这个字段**分不出注册与否。至于整个 HTTP 响应是不是也分不
   * 出，实测的边界（哪些逐字节相同、哪一种可区分、为什么可区分不算这个 API 在泄题、
   * 以及改成请求制之后这条保证比直通添加时弱在哪里）写在 actions.ts 里 `NOTICE`
   * 的注释上，比这里长，值得一读。
   */
  notice?: string;
};

/** 表单状态的初始值。必须是模块级常量：每次渲染新建一个 `{}` 会让 React 认为状态变了。 */
export const ADD_FRIEND_INITIAL: AddFriendFormState = {};
